#!/usr/bin/env node
/**
 * Concatenates supabase/migrations/*.sql (in order) into supabase/setup.sql,
 * so a fresh project can be set up with a single paste into the SQL Editor.
 *
 *   npm run db:bundle
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'supabase/migrations');
const files = fs.readdirSync(dir).filter((f) => /^\d+_.*\.sql$/.test(f)).sort();

const header = `-- =============================================================================
-- ECYR English — full database setup (generated by \`npm run db:bundle\`)
-- -----------------------------------------------------------------------------
-- Paste this whole file into Supabase → SQL Editor → New query → Run.
-- Safe to re-run: every statement is create-if-not-exists or drop-then-create.
-- Includes, in order: ${files.join(', ')}
-- Do not edit by hand: change supabase/migrations/* and re-run the script.
-- =============================================================================
`;

const body = files
  .map((f) => `\n\n-- >>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>> ${f}\n\n${fs.readFileSync(path.join(dir, f), 'utf8').trim()}\n`)
  .join('');
fs.writeFileSync(path.join(root, 'supabase/setup.sql'), header + body);
console.log(`✓ supabase/setup.sql  (${files.length} migrations)`);
